#!/usr/bin/env ruby
# frozen_string_literal: true
# Development-only finite facts for DuplicateMatchPattern's source identities.
# Project the same declared-encoding characters as Parser::Source::Buffer BEFORE
# sorting/inspection, including printable aliases and non-scalar expansions.
# No runtime codec, host Unicode dependency or semantic literal normalization.
# UTF8-MAC composition reuses generate_heredoc_uppercase.rb's bounded MAC facts;
# CESU-8 surrogate pairs and GB18030 dense four-byte keys are algorithmic.
# ruby tools/generate_source_inspection.rb > /tmp/source_inspection.rs
abort 'expected Unicode 15.0' unless RbConfig::CONFIG['UNICODE_VERSION'] == '15.0.0'
source = File.read(File.expand_path('../vendor/ruby-prism-sys/vendor/prism-1.9.0/src/encoding.c', __dir__))
names = source.scan(/\.name = "([^"]+)"/).flatten & Encoding.list.map(&:name)
names -= %w[UTF-8 US-ASCII ASCII-8BIT CESU-8 UTF8-MAC]
maps = []; ids = {}; expansions = []; expansion_ids = {}
names.each do |name|
  rows = []; expanded = []
  classify = lambda do |bytes|
    raw = bytes.pack('C*').force_encoding(name)
    next unless raw.valid_encoding? && raw.length == 1
    begin
      text = raw.encode('UTF-8')
      # Mobile UTF8 profiles differ only in their private-use projections.
      next if name.start_with?('UTF8-') && text.b == raw.b
      key = if name == 'GB18030' && bytes.length == 4
        a,b,c,d = bytes
        0x10000 + (((a - 0x81) * 10 + b - 0x30) * 126 + c - 0x81) * 10 + d - 0x30
      else
        bytes.reduce(0) { |v,b| (v << 8) | b }
      end
      if text.length == 1
        rows << [key, text.ord]
      else
        expanded << [key, text.b]
      end
    rescue EncodingError, NotImplementedError
      # Undefined mappings cannot populate the reference source buffer. Keep
      # them absent, never replace with U+FFFD or invent a conversion.
      next
    end
  end
  if name.start_with?('UTF8-')
    (0xe000..0xf8ff).each { |code| classify.call([code].pack('U').bytes) }
  else
    (128..255).each { |a| classify.call([a]) }
    (128..255).each { |a| (0..255).each { |b| classify.call([a,b]) } }
    if %w[EUC-JP eucJP-ms CP51932 EUC-JIS-2004].include?(name)
      (0xa1..0xfe).each { |a| (0xa1..0xfe).each { |b| classify.call([0x8f,a,b]) } }
    elsif name == 'GB18030'
      (0x81..0xfe).each { |a| (0x30..0x39).each { |b| (0x81..0xfe).each { |c| (0x30..0x39).each { |d| classify.call([a,b,c,d]) } } } }
    elsif name == 'EUC-TW'
      (0xa1..0xb0).each { |p| (0xa1..0xfe).each { |a| (0xa1..0xfe).each { |b| classify.call([0x8e,p,a,b]) } } }
    elsif name == 'Emacs-Mule' || name.start_with?('stateless-ISO-2022-JP')
      (0x90..0x9b).each { |head| (0xa0..0xff).each { |a| (0xa0..0xff).each { |b| classify.call([head,a,b]) } } }
      [[0x9c, 0xf0..0xf4], [0x9d, 0xf5..0xfe]].each do |head, planes|
        planes.each { |p| (0xa0..0xff).each { |a| (0xa0..0xff).each { |b| classify.call([head,p,a,b]) } } }
      end
    end
  end
  ranges = []
  rows.sort.uniq.each do |key,code|
    last = ranges.last
    if last && key == last[1] + 1 && code == last[2] + key - last[0]
      last[1] = key
    else
      ranges << [key,key,code]
    end
  end
  id = maps.index(ranges) || maps.length
  maps << ranges if id == maps.length
  ids[name] = id
  expanded.sort!.uniq!
  id = expansions.index(expanded) || expansions.length
  expansions << expanded if id == expansions.length
  expansion_ids[name] = id
end
puts <<~RUST
  //! Generated by tools/generate_source_inspection.rb (Ruby Unicode 15.0).
  //! Finite declared-encoding -> UTF8 source facts for DuplicateMatchPattern.
  //! GB18030 four-byte keys use the dense index documented in the generator.
  //! Undefined conversions are absent, not replacement characters.
  #[derive(Clone, Copy, Debug)]
  pub(super) struct Projection {
      pub scalars: &'static [(u32, u32, u32)],
      pub expansions: &'static [(u32, &'static [u8])],
  }
  pub(super) fn projection(name: &[u8]) -> Projection { match name {
RUST
ids.each { |name,id| puts "b\"#{name}\" => Projection { scalars: E#{id}, expansions: X#{expansion_ids.fetch(name)} }," }
puts '_ => Projection { scalars: &[], expansions: &[] }, } }'
maps.each_with_index do |ranges,id|
  puts "const E#{id}: &[(u32,u32,u32)] = &["
  ranges.each { |a,b,c| puts '(0x%x,0x%x,0x%x),' % [a,b,c] }
  puts '];'
end
expansions.each_with_index do |rows,id|
  puts "const X#{id}: &[(u32, &[u8])] = &["
  rows.each { |key,text| puts '(0x%x, b"%s"),' % [key, text.bytes.map { |b| '\\x%02x' % b }.join] }
  puts '];'
end
# Ruby String#inspect escapes precisely these classes, using Ruby's pinned
# Unicode 15.0 assignments (not the host Rust/regex crate's evolving tables).
nonprint = []
(0..0x10ffff).each do |code|
  next if (0xd800..0xdfff).cover?(code)
  next unless /[\p{Cc}\p{Cn}\p{Zl}\p{Zp}]/.match?([code].pack('U'))
  if nonprint.last && code == nonprint.last[1] + 1
    nonprint.last[1] = code
  else
    nonprint << [code, code]
  end
end
puts <<~RUST
  pub(super) fn unicode_nonprint(code: u32) -> bool {
      UNICODE.get(UNICODE.partition_point(|&(_, end)| end < code))
          .is_some_and(|&(start, _)| start <= code)
  }
  const UNICODE: &[(u32, u32)] = &[
RUST
nonprint.each { |a,b| puts '(0x%x,0x%x),' % [a,b] }
puts '];'
