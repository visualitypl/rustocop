# frozen_string_literal: true
# Trusted runtime metadata ONLY. No inspected Ruby source is loaded/evaluated.
# Run with the pinned oracle runtime and a native Ruby 3.4 (RUSTOCOP_RUBY34).
require_relative 'oracle/oracle'
Oracle.load_rubocop(Oracle.locate_rubocop(nil))
reference = Oracle.locate_rubocop(nil)
inventory = JSON.parse(File.read(File.expand_path('oracle/lint_reference.json', __dir__)))
raise 'wrong reference revision' unless Oracle.rubocop_revision(reference) == inventory.fetch('reference').fetch('revision')
inventory.fetch('reference_files').each do |path, hash|
  next unless path.start_with?('lib/')
  raise "reference hash #{path}" unless Digest::SHA256.file(File.join(reference, path)).hexdigest == hash
end
require 'open3'

module ShadowedExceptionConstants
  PATH = File.expand_path('../src/cops/lint/shadowed_exception_constants.tsv', __dir__)
  # No autoload is followed, no arbitrary const_missing, and no application path
  # is opened. const_get(false) is called ONLY on enumerated loaded constants.
  PROBE = <<~'RUBY'
    $VERBOSE = nil
    queue = [Object]
    seen = {}
    rows = []
    until queue.empty?
      mod = queue.shift
      next if seen[mod.object_id]
      seen[mod.object_id] = true
      name = Module.instance_method(:name).bind_call(mod)
      next unless name && !name.empty?
      next if name.match?(/\A(?:Oracle|FixedPolicy|ShadowedExceptionConstants|Minitest)(?:::|\z)/)
      chain = Module.instance_method(:ancestors).bind_call(mod)
      ancestors = chain.filter_map { |a| Module.instance_method(:name).bind_call(a) }
      rows << ['A', name, *ancestors].join("\t")
      if chain[1] == SystemCallError && Module.instance_method(:const_defined?).bind_call(mod, :Errno, false)
        rows << ['E', name, Module.instance_method(:const_get).bind_call(mod, :Errno, false)].join("\t")
      end
      Module.instance_method(:constants).bind_call(mod, false).sort.each do |key|
        next if Module.instance_method(:autoload?).bind_call(mod, key)
        value = Module.instance_method(:const_get).bind_call(mod, key, false)
        next unless value.is_a?(Module)
        value_name = Module.instance_method(:name).bind_call(value)
        next unless value_name
        next if value_name.match?(/\A(?:Oracle|FixedPolicy|ShadowedExceptionConstants|Minitest)(?:::|\z)/)
        rows << ['C', name, key, value_name].join("\t")
        queue << value
      rescue NameError
        # A concurrent/unsupported runtime constant is not a known fact.
      end
    end
    puts rows.sort
  RUBY
  def self.collect
    ruby = ENV.fetch('RUSTOCOP_RUBY34')
    version, status = Open3.capture2(ruby, '--version')
    raise 'native Ruby3.4 required' unless status.success? && version.start_with?('ruby 3.4.')
    # This is a fixed trusted metadata program, never an inspected snippet.
    native, err, status = Open3.capture3(ruby, '-e', PROBE)
    raise err unless status.success?
    # Clean trusted runtime: no Oracle/RSpec/test helper constants leak into
    # production metadata. Only the finite pinned shipped registry is forced;
    # digest/sha2 is the fixed trusted checksum library, not a source request.
    host, err, status = Open3.capture3(RbConfig.ruby, '-I', File.join(Oracle.locate_rubocop(nil), 'lib'), '-rrubocop', '-rdigest/sha2', '-e', "RuboCop::Cop::Registry.global.to_a\n" + PROBE)
    raise err unless status.success?
    rows = host.lines.map { |l| l.chomp.split("\t") }
    native_rows = native.lines.map { |l| l.chomp.split("\t") }
    core = native_rows.select { |r| r[0] == 'A' }.map { |r| r[1] }
    bare_host, err, status = Open3.capture3(RbConfig.ruby, '--disable-gems', '-e', PROBE)
    raise err unless status.success?
    old_core = bare_host.lines.map { |l| l.chomp.split("\t") }.select { |r| r[0]=='A' }.map { |r| r[1] }
    removed = old_core - core
    rows.reject! { |r| removed.any? { |name| r[1]==name || r[1].start_with?(name+'::') || (r[0]=='C' && r[3]==name) } }
    # Native core/Errno aliases are authoritative. Preserve reference-loaded
    # mixins (e.g. JSON) not present in a bare native process.
    facts = rows.to_h { |r| [[r[0],r[1],r[0]=='C' ? r[2] : nil],r] }
    native_rows.each do |r|
      key = [r[0],r[1],r[0]=='C' ? r[2] : nil]
      if r[0] == 'A' && (prior = facts[key])
        r += prior.drop(2).reject { |a| core.include?(a) || r.drop(2).include?(a) }
      end
      facts[key] = r
    end
    # A core constant removed by Ruby3.4 must not survive from the host.
    native_keys = native_rows.select { |r| r[0]=='C' }.map { |r| [r[1],r[2]] }
    facts.delete_if { |_,r| r[0]=='C' && core.include?(r[1]) && core.include?(r[3]) && !native_keys.include?([r[1],r[2]]) }
    "# Fixed #{version.strip} core/Linux Errno + pinned RuboCop1.92.0 loaded runtime (host #{RUBY_VERSION}).\n# Generated by tools/generate_shadowed_exception_constants.rb; never follows source-selected autoload.\n" + facts.values.map { |r| r.join("\t") }.sort.join("\n") + "\n"
  end
end
if $PROGRAM_NAME == __FILE__
  data = ShadowedExceptionConstants.collect
  if ARGV == ['--check']
    abort 'constant snapshot differs' unless File.binread(ShadowedExceptionConstants::PATH) == data
  elsif ARGV.empty?
    File.binwrite(ShadowedExceptionConstants::PATH, data)
  else
    abort 'usage: ruby tools/generate_shadowed_exception_constants.rb [--check]'
  end
end
