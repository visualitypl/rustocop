#!/usr/bin/env ruby
# frozen_string_literal: true
# Development-only heredoc collision spelling after the pinned source buffer's
# UTF-8 projection. Encode uppercase back to source bytes for exact body matching.
# Unrepresentable uppercase has no possible body spelling in that encoding.
# ruby tools/generate_heredoc_uppercase.rb > /tmp/heredoc_uppercase.rs
abort 'expected Unicode 15.0' unless RbConfig::CONFIG['UNICODE_VERSION'] == '15.0.0'
source = File.read(File.expand_path('../vendor/ruby-prism-sys/vendor/prism-1.9.0/src/encoding.c', __dir__))
names = source.scan(/\.name = "([^"]+)"/).flatten & Encoding.list.map(&:name)
names -= %w[UTF-8 US-ASCII ASCII-8BIT CESU-8 UTF8-MAC UTF8-DoCoMo UTF8-KDDI UTF8-SoftBank]
maps = []; ids = {}; aliases = []; alias_ids = {}; folds = []; fold_ids = {}
names.each do |name|
  rows = []; normalization = []; folded = []
  classify = lambda do |bytes|
    s = bytes.pack('C*').force_encoding(name)
    next unless s.valid_encoding? && s.length == 1
    begin
      projected = s.encode('UTF-8')
      folded << bytes.reduce(0) { |v,b| (v<<8)|b } if /\A[A-Z]\z/i.match?(projected)
      canonical = projected.encode(name).b
      normalization << [bytes.reduce(0) { |v,b| (v<<8)|b }, canonical] if canonical != s.b
      next if projected == projected.upcase
      upper = projected.upcase.encode(name).b
      rows << [bytes.reduce(0) { |v,b| (v<<8)|b }, upper]
    rescue EncodingError
      next
    end
  end
  (128..255).each { |a| classify.call([a]) }
  (128..255).each { |a| (0..255).each { |b| classify.call([a,b]) } }
  if %w[EUC-JP eucJP-ms CP51932 EUC-JIS-2004].include?(name)
    (0xa1..0xfe).each { |a| (0xa1..0xfe).each { |b| classify.call([0x8f,a,b]) } }
  elsif name == 'GB18030'
    (0x81..0xfe).each { |a| (0x30..0x39).each { |b| (0x81..0xfe).each { |c| (0x30..0x39).each { |d| classify.call([a,b,c,d]) } } } }
  elsif name == 'EUC-TW'
    (0xa1..0xb0).each { |p| (0xa1..0xfe).each { |a| (0xa1..0xfe).each { |b| classify.call([0x8e,p,a,b]) } } }
  end
  rows.sort!.uniq!
  id = maps.index(rows) || maps.length
  maps << rows if id == maps.length
  ids[name] = id
  normalization.sort!.uniq!
  id = aliases.index(normalization) || aliases.length
  aliases << normalization if id == aliases.length
  alias_ids[name] = id
  folded.sort!.uniq!
  id = folds.index(folded) || folds.length
  folds << folded if id == folds.length
  fold_ids[name] = id
end
puts <<~RUST
  //! Generated by tools/generate_heredoc_uppercase.rb (Ruby Unicode 15.0).
  //! Pinned uppercase spellings in the original source encoding, for collision
  //! detection only. No Ruby runtime, codec or candidate parse in the linter.
  pub(super) fn legacy(name: &[u8]) -> &'static [(u32, &'static [u8])] { match name {
RUST
ids.each { |name,id| puts "b\"#{name}\" => E#{id}," }
puts '_ => &[], } }'
puts "pub(super) fn aliases(name: &[u8]) -> &'static [(u32, &'static [u8])] { match name {"
alias_ids.each { |name,id| puts "b\"#{name}\" => A#{id}," }
puts '_ => &[], } }'
puts "pub(super) fn ascii_letters(name: &[u8]) -> &'static [u32] { match name {"
fold_ids.each { |name,id| puts "b\"#{name}\" => F#{id}," }
puts '_ => &[], } }'
folds.each_with_index { |codes,id| puts "const F#{id}: &[u32] = &[#{codes.map { |c| '0x%x' % c }.join(',')}];" }
puts "pub(super) fn mobile_words(name: &[u8]) -> &'static [(u32, &'static [u8])] { match name {"
%w[UTF8-DoCoMo UTF8-KDDI UTF8-SoftBank].each_with_index { |name,id| puts "b\"#{name}\" => M#{id}," }
puts '_ => &[], } }'
%w[UTF8-DoCoMo UTF8-KDDI UTF8-SoftBank].each_with_index do |name,id|
  puts "const M#{id}: &[(u32, &[u8])] = &["
  (0xe000..0xf8ff).each do |code|
    raw = [code].pack('U').force_encoding(name)
    begin
      projected = raw.encode('UTF-8')
      next unless /\w/.match?(projected)
      packed = raw.bytes.reduce(0) { |v,b| (v<<8)|b }
      puts "(0x#{packed.to_s(16)}, b\"#{projected.bytes.map { |b| '\\x%02x' % b }.join}\"),"
    rescue EncodingError
      next
    end
  end
  puts '];'
end
puts "pub(super) const UNICODE: &[(u32, &str)] = &["
(128..0x10ffff).each do |code|
  next if (0xd800..0xdfff).cover?(code)
  s = [code].pack('U'); upper = s.upcase
  next if upper == s
  puts "(0x#{code.to_s(16)}, \"#{upper.codepoints.map { |c| "\\u{#{c.to_s(16)}}" }.join}\"),"
end
puts '];'
# UTF8-MAC's source-buffer projection composes decomposed input. Hangul is
# algorithmic in the consumer; keep only bounded non-Hangul prefixes here.
# Every partition of a decomposition can already have composed chunks (e.g.
# a + ring + acute can arrive as å + acute). Project each chunk with the same
# codec, not general NFC, which differs from the pinned UTF8-MAC tables.
def mac_spellings(chars)
  return [''.b] if chars.empty?

  (1..chars.length).flat_map do |n|
    head = chars.take(n).join.force_encoding('UTF8-MAC').encode('UTF-8').b
    mac_spellings(chars.drop(n)).map { |tail| head + tail }
  end.uniq
end
mac = {}
(0..0x10ffff).each do |code|
  next if (0xd800..0xdfff).cover?(code) || (0xac00..0xd7a3).cover?(code)
  s = [code].pack('U')
  begin
    raw = s.encode('UTF8-MAC').b
    projected = raw.dup.force_encoding('UTF8-MAC').encode('UTF-8').b
    if raw != projected
      spellings = [raw, *mac_spellings(raw.dup.force_encoding('UTF-8').chars)]
      spellings.each do |spelling|
        canonical = spelling.dup.force_encoding('UTF8-MAC').encode('UTF-8').b
        mac[spelling] = canonical if spelling != canonical
      end
    end
  rescue EncodingError
    next
  end
end
puts 'pub(super) const MAC: &[(&[u8], &[u8])] = &['
mac.sort.each do |raw, projected|
  escaped = ->(s) { 'b"' + s.bytes.map { |b| '\\x%02x' % b }.join + '"' }
  puts "(#{escaped.call(raw)}, #{escaped.call(projected)}),"
end
puts '];'
[['E',maps], ['A',aliases]].each do |prefix, groups|
  groups.each_with_index do |rows,id|
    puts "const #{prefix}#{id}: &[(u32, &[u8])] = &["
    rows.each { |code, upper| puts "(0x#{code.to_s(16)}, b\"#{upper.bytes.map { |b| '\\x%02x' % b }.join}\")," }
    puts '];'
  end
end
