#[test]
fn every_test_file_is_part_of_this_program() {
    let declared = include_str!("main.rs");
    let mut missing = Vec::new();
    for entry in std::fs::read_dir(concat!(env!("CARGO_MANIFEST_DIR"), "/tests")).unwrap() {
        let path = entry.unwrap().path();
        if path.extension().is_none_or(|extension| extension != "rs") {
            continue;
        }
        let name = path.file_stem().unwrap().to_str().unwrap().to_owned();
        let listed = [format!("\nmod {name};\n"), format!("\nmod r#{name};\n")];
        if name != "main" && !listed.iter().any(|line| declared.contains(line.as_str())) {
            missing.push(name);
        }
    }
    assert!(missing.is_empty(), "add to tests/main.rs: {missing:?}");
}
